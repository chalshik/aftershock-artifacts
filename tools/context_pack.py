"""Write docs/context-pack.md, the generated start-of-session pack. Never edit that file by hand. Stdlib only.

    python3 tools/context_pack.py            # (re)write docs/context-pack.md
    python3 tools/context_pack.py --digest   # print a short digest (<= DIGEST_MAX chars) for the session-start hook

The pack holds, in order: status, PROTOCOL, definitions, the model ledger, the open items of open-questions.md,
and the last N_DECISIONS decisions.md entries. It carries no commit hash or date, so the same sources always give
the same file and tools/check_docs.py can tell a stale or hand-edited pack.
"""
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
N_DECISIONS = 5
DIGEST_MAX = 9500  # Claude Code caps SessionStart context at 10,000 characters (docs, hooks: SessionStart)
SOURCES = ["docs/status.md", "PROTOCOL.md", "docs/definitions.md", "docs/model.md"]
READ_ORDER = ["docs/context-pack.md", "docs/status.md", "PROTOCOL.md", "docs/definitions.md", "docs/model.md",
              "docs/open-questions.md (open items)"]


def _read(p: str) -> str:
    f = REPO / p
    return f.read_text() if f.exists() else f"**MISSING: {p}** (stop and report, CLAUDE.md session protocol)\n"


def open_items(text: str) -> list[str]:
    """Table rows of open-questions.md whose answer is open or partly answered."""
    return [l for l in text.splitlines() if l.startswith("|") and re.search(r"\|\s*\*\*(Open|Partly)", l)]


def last_entries(text: str, n: int) -> list[str]:
    parts = re.split(r"(?m)^(?=## )", text)
    return [p.rstrip() + "\n" for p in parts if p.startswith("## ")][-n:]


def build() -> str:
    out = ["<!-- GENERATED by tools/context_pack.py. Do not edit; regenerate. -->\n", "# Context pack\n",
           "Read order: " + " → ".join(f"`{p}`" for p in READ_ORDER) + "\n"]
    for p in SOURCES:
        out.append(f"\n---\n\n<!-- source: {p} -->\n\n" + _read(p).replace("\n# ", "\n## ").lstrip())
    oq = _read("docs/open-questions.md")
    out.append("\n---\n\n<!-- source: docs/open-questions.md, open items only -->\n\n## Open questions (open items)\n\n"
               "| # | Question | Answer | Evidence |\n|---|---|---|---|\n" + "\n".join(open_items(oq)) + "\n")
    out.append(f"\n---\n\n<!-- source: docs/decisions.md, last {N_DECISIONS} entries -->\n\n## Last decisions\n\n"
               + "\n".join(e.replace("\n## ", "\n### ").replace("## ", "### ", 1) for e in last_entries(_read("docs/decisions.md"), N_DECISIONS)))
    return "".join(out)


def _section(text: str, start: str, stop: str = "\n## ") -> str:
    i = text.find(start)
    if i < 0:
        return ""
    j = text.find(stop, i + len(start))
    return text[i: j if j > 0 else None].strip()


def digest() -> str:
    """Short text for the session-start hook: what to read, current state, open risks, and stale/missing warnings."""
    status = _read("docs/status.md")
    pack = REPO / "docs/context-pack.md"
    warn = []
    missing = [p for p in ["docs/status.md", "PROTOCOL.md", "docs/definitions.md", "docs/model.md",
                           "docs/open-questions.md", "docs/process.md", "docs/claims.md"] if not (REPO / p).exists()]
    if missing:
        warn.append("MISSING FILES: " + ", ".join(missing) + ". Stop and report before anything else.")
    if not pack.exists() or pack.read_text() != build():
        warn.append("docs/context-pack.md is missing or stale: run `python3 tools/context_pack.py`, then report it.")
    head = status.split("\n## ", 1)[0]
    parts = ["SESSION START (aftershock-artifacts). Rules: CLAUDE.md. Read in this order, then give the first reply "
             "(files read, one-paragraph state, what you will do): " + " → ".join(READ_ORDER) + ".",
             *warn, head.strip(), _section(status, "## Open risks"), _section(status, "## Watch"),
             "Open items: " + "; ".join(re.split(r"\s*\|\s*", l)[1] for l in open_items(_read("docs/open-questions.md"))),
             "Last decisions: " + " / ".join(e.splitlines()[0][3:] for e in last_entries(_read("docs/decisions.md"), N_DECISIONS))]
    text = "\n\n".join(p for p in parts if p)
    return text if len(text) <= DIGEST_MAX else text[: DIGEST_MAX - 60] + "\n…[digest cut; read docs/context-pack.md]"


def main(argv: list[str]) -> int:
    if "--digest" in argv:
        print(digest())
        return 0
    (REPO / "docs/context-pack.md").write_text(build())
    print("wrote docs/context-pack.md")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
