# Synthetic model-F simulation (no run data): FIFO single server, closed-loop turns, all-miss after the burst start.
import sys, heapq, math, numpy as np
sys.path.insert(0, "/Users/chalshik/Projects/aftershock-artifacts")
from analysis import modelf, k3
T=8; L=modelf.l1_prompts(T); MU=1.681
tok_s = 1/(MU*np.mean(L))   # s per token, stationary-mix all-miss throughput = MU
def run(lam, seed, gap=0.0, warm=0.6, brate=3.0, bdur=180, at=900, watch=1500, mu_true=MU):
    rng=np.random.default_rng(seed); tk=1/(mu_true*np.mean(L))
    end=at+bdur; dur=end+watch
    n=rng.poisson(lam/T*dur); starts=np.sort(rng.uniform(0,dur,n))
    bt=at+np.sort(rng.uniform(0,bdur,rng.poisson(brate*bdur)))
    # events: arrivals to FIFO queue (time, seq, sid, turn); burst sid=-1
    ev=[(t,i,s,0) for i,(s,t) in enumerate(enumerate(starts))]+[(t,10**7+i,-1,0) for i,t in enumerate(bt)]
    heapq.heapify(ev); seq=2*10**7
    free=0.0; comp=[]   # (t_end, sid, turn)
    # FIFO single server: process in arrival order; arrivals generated by completions -> need event loop
    q=[]
    while ev:
        t,_,s,k=heapq.heappop(ev)
        start=max(t,free)
        cost=(2944 if s<0 else L[k])*tk*(warm if (start<at and s>=0) else 1.0)
        free=start+cost; comp.append((free,s,k))
        if s>=0 and k<T-1:
            nt=free+(rng.exponential(gap) if gap>0 else 0.0)
            if nt<dur: seq+=1; heapq.heappush(ev,(nt,seq,s,k+1))
    # FIFO by arrival time is honored because heap pops by time and server serves in pop order (arrival order)
    a,b=end+600,dur
    c=np.array([(te,s,k) for te,s,k in comp if s>=0 and a<=te<b])
    kb=(c[:,2]+1).mean(); last=(c[:,2]==T-1).sum()
    nst=((starts>=a)&(starts<b)).sum(); lamW=T*nst/(b-a)
    zh=k3.z_from_kbar(kb,T); rhoW=lamW/MU
    tF=modelf.trap(modelf.fixed_turns(T),L,rhoW)
    muh=lamW/k3.rho_of_z(zh,L) if zh>1 else float('nan')
    return dict(kb=kb,kF=k3.kbar_of_z(tF.z,T),d=last/nst,dmix=zh**-T,dF=tF.z**-T,muh=muh,X=len(c)/(b-a)/MU,
                h1=k3.kbar_obs and None)
for lam in (2.0,2.4):
  for gap in (0.0,30.0):
    R=[run(lam,s,gap=gap) for s in range(40)]
    f=lambda key: np.array([r[key] for r in R])
    dk=f('kb')-f('kF'); dm=f('d')-f('dmix'); df=f('d')-f('dF')
    print(f"lam={lam} gap={gap}: kbar_obs {f('kb').mean():.3f}+-{f('kb').std():.3f} kF {f('kF').mean():.3f}+-{f('kF').std():.3f} | Q1 dev {dk.mean():+.3f} sd {dk.std():.3f} | d_obs {f('d').mean():.3f} sd {f('d').std():.3f} Q2' dev {dm.mean():+.3f} sd {dm.std():.3f} Q2 dev {df.mean():+.3f} | mu_hat {np.nanmean(f('muh')):.3f} sd {np.nanstd(f('muh')):.3f} nan {np.isnan(f('muh')).sum()} | X/mu {f('X').mean():.3f}")
